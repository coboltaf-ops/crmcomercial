// ──────────────────────────────────────────────────────────────────────────
// Mapas del dashboard por país (multipaís).
//
// Cada país aporta: el recuadro de proyección (bounds lat/lon), el contorno del
// país, opcionalmente sus provincias/departamentos y las coordenadas de sus
// ciudades. El dashboard elige el mapa según el país filtrado.
//
// Sumar un país nuevo = agregar una entrada aquí (ver src/shared/lib/paises.ts).
// Formato de puntos: [latitud, longitud].
// ──────────────────────────────────────────────────────────────────────────
import { DEPARTAMENTOS } from './colombia-departamentos'

export interface MapaPais {
  /** Recuadro geográfico que encuadra al país (para proyectar lat/lon → SVG). */
  bounds: { latMin: number; latMax: number; lonMin: number; lonMax: number }
  /** Contorno del país continental · [lat, lon]. */
  borde: [number, number][]
  /** Provincias/departamentos (opcional) · [lat, lon]. */
  provincias?: { nombre: string; puntos: [number, number][] }[]
  /** Coordenadas de ciudades (clave normalizada → [lat, lon]). */
  ciudades: Record<string, [number, number]>
}

/** Normaliza un nombre de ciudad para buscarlo en `ciudades`. */
export const normCiudad = (s: string) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').trim()

